fun PrivChatAssistantConversationStrings.executionState(state: String?): String? = when (state) {
    "accepted", "dispatched" -> accepted
    "running" -> running
    "cancelling" -> cancelling
    "waiting_user", "waiting_permission" -> waiting
    "succeeded" -> completed
    "failed" -> failed
    "cancelled" -> cancelled
    else -> null
}
